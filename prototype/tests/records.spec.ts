import { test, expect } from '@playwright/test'

test('a new back bookmark survives reload and finishing its follow-up clears the reminder', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '切换到爸爸', exact: true }).click()
  await page.getByRole('button', { name: '记录新变化', exact: true }).click()
  await page.getByLabel('观察部位', { exact: true }).selectOption('背部')
  await page.getByLabel('位置备注').fill('背部 · 新的观察')
  await page.getByRole('button', { name: '开始记录', exact: true }).click()
  await page.getByRole('button', { name: '无明显不适', exact: true }).click()
  await page.getByRole('button', { name: '刚出现', exact: true }).click()
  await page.getByRole('button', { name: '基本不变', exact: true }).click()
  await page.getByRole('button', { name: '查看本次观察', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '将本次照片保存在本地手账' })).toBeDisabled()
  await page.getByRole('button', { name: '保存本次记录', exact: true }).click()
  await expect(page.getByTestId('body-map')).toHaveAttribute('data-view', 'back')
  await expect(page.getByRole('button', { name: '查看背部 · 新的观察', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('spot-title')).toHaveText('背部 · 新的观察')
  await page.getByRole('button', { name: '安排复查', exact: true }).click()
  await page.getByLabel('复查日期').fill('2026-11-18')
  await page.getByRole('button', { name: '保存复查计划', exact: true }).click()
  await page.getByRole('button', { name: '为这一处复查', exact: true }).click()
  await page.getByRole('button', { name: '无明显不适', exact: true }).click()
  await page.getByRole('button', { name: '几天', exact: true }).click()
  await page.getByRole('button', { name: '基本不变', exact: true }).click()
  await page.getByRole('button', { name: '查看本次观察', exact: true }).click()
  await page.getByRole('button', { name: '保存本次记录', exact: true }).click()
  await page.getByRole('button', { name: '复查计划', exact: true }).click()
  await expect(page.getByText('2026-11-18', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '身体手账', exact: true }).click()
  await page.getByRole('button', { name: '前后对照', exact: true }).click()
  await expect(page.getByRole('button', { name: '滑动对照', exact: true })).toBeDisabled()
  await expect(page.getByText('本次未保存照片', { exact: true })).toHaveCount(2)
})

test('member rename and confirmed deletion preserve other family journals', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '家庭成员', exact: true }).click()
  const row = page.locator('.family-row').filter({ has: page.getByRole('heading', { name: '妈妈', exact: true }) })
  await row.getByRole('button', { name: '修改称呼', exact: true }).click()
  await page.getByRole('textbox', { name: '成员称呼', exact: true }).fill('母亲')
  await page.getByRole('button', { name: '保存称呼', exact: true }).click()
  await expect(page.getByRole('heading', { name: '母亲', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除成员母亲', exact: true }).click()
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page.getByRole('heading', { name: '母亲', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '删除成员母亲', exact: true }).click()
  await page.getByRole('button', { name: '确认删除这位成员', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('这位成员的本地手账已删除')
  await page.reload()
  await expect(page.getByRole('button', { name: '切换到母亲', exact: true })).toHaveCount(0)
  await expect(page.getByTestId('spot-title')).toHaveText('左前臂 · 外侧')
})

test('clearing all records stays empty after reload and a first member can start without login', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '本地档案与设置', exact: true }).click()
  await page.getByRole('button', { name: '清空本地记录', exact: true }).click()
  await page.getByRole('button', { name: '确认清空所有记录', exact: true }).click()
  await expect(page.getByRole('button', { name: '建立第一位成员', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '建立第一位成员', exact: true }).click()
  await page.getByLabel('成员称呼').fill('自己')
  await page.getByRole('button', { name: '建立手账', exact: true }).click()
  await expect(page.getByRole('button', { name: '切换到自己', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '切换到妈妈', exact: true })).toHaveCount(0)
  await expect(page.getByText('从第一条观察开始', { exact: true })).toBeVisible()
})
