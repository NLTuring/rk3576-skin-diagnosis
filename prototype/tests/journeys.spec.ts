test('camera rejection has a clear import fallback and does not lose draft notes', async ({ page }) => {
  await page.addInitScript(() => {
    Object.defineProperty(navigator.mediaDevices, 'getUserMedia', {
      value: () => Promise.reject(new DOMException('Permission denied', 'NotAllowedError')),
    })
  })
  await startFollowup(page)
  await page.getByLabel('补充一句话').fill('保留草稿')
  await page.getByRole('button', { name: '摄像头拍摄', exact: true }).click()
  await expect(page.getByText('无法使用摄像头', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '改用已有照片', exact: true }).click()
  await expect(page.getByLabel('补充一句话')).toHaveValue('保留草稿')
})
