import { expect, test } from '@playwright/test'
import path from 'node:path'

const fixture = path.resolve('public/media/arm-reference.png')
async function startFollowup(page: import('@playwright/test').Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '为这一处复查', exact: true }).click()
  await expect(page.getByRole('heading', { name: '记录今天的变化。' })).toBeVisible()
}
async function fillSymptoms(page: import('@playwright/test').Page) {
  await page.getByRole('button', { name: '痒', exact: true }).click()
  await page.getByRole('button', { name: '几天', exact: true }).click()
  await page.getByRole('button', { name: '基本不变', exact: true }).click()
}
test('real image is not diagnosed; unchecked photo is not retained after reload', async ({ page }) => {
  const outgoing: string[] = []
  page.on('request', request => { if (request.method() !== 'GET') outgoing.push(request.url()) })
  await startFollowup(page)
  await page.getByLabel('选择皮肤照片').setInputFiles(fixture)
  await fillSymptoms(page)
  await page.getByLabel('补充一句话').fill('一条个人观察记录')
  await page.getByRole('button', { name: '查看本次观察', exact: true }).click()
  await expect(page.getByText('本次尚未进行 AI 识别', { exact: true })).toBeVisible()
  await expect(page.getByText('湿疹 / 皮炎类表现', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: '将本次照片保存在本地手账' })).not.toBeChecked()
  await page.getByRole('button', { name: '保存本次记录', exact: true }).click()
  await expect(page.getByText('本次未保存照片', { exact: true }).first()).toBeVisible()
  await page.reload()
  await expect(page.getByText('一条个人观察记录', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('本次未保存照片', { exact: true }).first()).toBeVisible()
  expect(outgoing).toEqual([])
})
test('consented image survives reload and can be explicitly deleted', async ({ page }) => {
  await startFollowup(page)
  await page.getByLabel('选择皮肤照片').setInputFiles(fixture)
  await fillSymptoms(page)
  await page.getByRole('button', { name: '查看本次观察', exact: true }).click()
  await page.getByRole('checkbox', { name: '将本次照片保存在本地手账' }).check()
  await page.getByRole('button', { name: '保存本次记录', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('照片与观察记录已保存在本地')
  await page.reload()
  await expect(page.getByRole('img', { name: '本次保存的照片' })).toHaveAttribute('src', /^data:image\/jpeg;base64,/)
  await page.getByRole('button', { name: '查看本次记录详情', exact: true }).click()
  await page.getByRole('button', { name: '仅删除照片', exact: true }).click()
  await page.getByRole('button', { name: '确认删除照片', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('照片已删除')
  await page.reload()
  await expect(page.getByText('本次未保存照片', { exact: true }).first()).toBeVisible()
})
